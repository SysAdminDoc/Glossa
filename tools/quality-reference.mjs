// Refreshes src/shared/quality-reference.ts: Google Translate's COMET22 score on the FLORES+ test set
// for every pair Mozilla evaluated, from Mozilla's own evaluation database. Glossa compares the model
// it is about to download (whose score comes from Mozilla's registry at run time) against it, and
// calls a pair's quality "lower" when it trails by a clear margin. Also prints where each released
// model stands today, which is what the README's quality paragraph quotes.
//
//   node tools/quality-reference.mjs
//
// Downloads about 40 MB (the database) into .tmp/ and the 200 KB registry. Needs Node 24 (node:sqlite).
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUCKET = "https://storage.googleapis.com/moz-fx-translations-data--303e-prod-translations-data/db";
const databasePath = path.join(root, ".tmp", "translations-db.sqlite");
const outputPath = path.join(root, "src", "shared", "quality-reference.ts");

async function download(url, target) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  await writeFile(target, new Uint8Array(await response.arrayBuffer()));
}

async function main() {
  await mkdir(path.dirname(databasePath), { recursive: true });
  await download(`${BUCKET}/db.sqlite`, databasePath);
  console.info(`quality: database ${Math.round((await stat(databasePath)).size / 1e6)} MB`);
  const registry = await (await fetch(`${BUCKET}/models.json`)).json();

  const database = new DatabaseSync(databasePath, { readOnly: true });
  const rows = database
    .prepare(
      `select e.source_lang as source, e.target_lang as target, m.corpus_score as score
         from final_evals e join final_eval_metrics m on m.eval_id = e.id
        where e.dataset = 'flores200-plus' and m.metric_name = 'comet22' and e.translator = 'google'
        order by e.source_lang, e.target_lang`
    )
    .all();
  database.close();
  const google = Object.fromEntries(rows.map((row) => [`${row.source}->${row.target}`, Number(row.score.toFixed(4))]));
  if (Object.keys(google).length < 50) throw new Error(`only ${Object.keys(google).length} Google scores found`);

  const lines = Object.entries(google).map(([pair, score]) => `  "${pair}": ${score}`);
  const source = `// Generated by tools/quality-reference.mjs from Mozilla's translations evaluation database
// (${BUCKET}/db.sqlite, registry generated ${registry.generated}). Do not edit by hand.
// Google Translate's COMET22 on the FLORES+ test set, the same test Mozilla scores its own models on.
export const GOOGLE_COMET22: Readonly<Record<string, number>> = {
${lines.join(",\n")}
};
`;
  await writeFile(outputPath, source);
  console.info(`quality: wrote ${Object.keys(google).length} pairs to ${path.relative(root, outputPath)}`);

  // Where the released models stand, for the README.
  const gaps = [];
  for (const models of Object.values(registry.models)) {
    for (const model of models) {
      const status = String(model.releaseStatus ?? "");
      const score = model.metrics?.["flores200-plus"]?.comet22;
      const key = `${model.sourceLanguage}->${model.targetLanguage}`;
      if (!status.startsWith("Release") || typeof score !== "number" || google[key] === undefined) continue;
      gaps.push({ key, architecture: model.architecture, score, gap: (google[key] - score) * 100 });
    }
  }
  gaps.sort((a, b) => b.gap - a.gap);
  const mean = gaps.reduce((sum, entry) => sum + entry.gap, 0) / gaps.length;
  console.info(`quality: ${gaps.length} released models, ${mean.toFixed(1)} points behind Google on average`);
  for (const entry of gaps.slice(0, 12)) {
    console.info(`  ${entry.key.padEnd(8)} ${entry.architecture.padEnd(12)} ${(entry.score * 100).toFixed(1)}  ${entry.gap.toFixed(1)} behind`);
  }
  const ahead = gaps.filter((entry) => entry.gap < 0);
  console.info(`quality: ahead of Google on ${ahead.length} (${ahead.map((entry) => entry.key).join(", ") || "none"})`);
  // Read it back, so a broken write fails here rather than in the build.
  if (!(await readFile(outputPath, "utf8")).includes("GOOGLE_COMET22")) throw new Error("the reference file was not written");
}

main().catch((error) => {
  console.error(`quality: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
